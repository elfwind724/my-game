/**
 * Weapon definitions - base weapons, evolved weapons, and evolution recipes
 * Vampire Survivors style: auto-fire, level up to 8, evolve with passive
 */

export interface WeaponDef {
  id: string;
  name: string;
  nameCN: string;
  description: string;
  descriptionCN: string;
  damage: number;
  fireRate: number; // ms between shots
  range: number;
  speed: number; // projectile speed
  spread: number; // degrees
  projectileCount: number;
  color: number;
  special?: 'burn' | 'pierce' | 'explode' | 'slow' | 'chain' | 'none';
  // Per-level scaling
  damagePerLevel: number;
  fireRatePerLevel: number; // negative = faster
  // Evolution
  evolvesWith?: string; // passive id required
  evolvesInto?: string; // evolved weapon id
  isEvolved?: boolean;
  rarity: 'common' | 'uncommon' | 'rare' | 'epic' | 'legendary';
}

