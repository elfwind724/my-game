// Get all base (non-evolved) weapons
export function getBaseWeapons(): WeaponDef[] {
  return Object.values(WEAPON_DEFS).filter(w => !w.isEvolved);
}

// Get weapon stats at a specific level
export function getWeaponAtLevel(weaponId: string, level: number): WeaponDef | null {
  const base = WEAPON_DEFS[weaponId];
  if (!base) return null;
  return {
    ...base,
    damage: base.damage + base.damagePerLevel * (level - 1),
    fireRate: Math.max(30, base.fireRate + base.fireRatePerLevel * (level - 1)),
  };
}

